//go:embed templates/*.tmpl
var templateFiles embed.FS

var (
	errDrift       = errors.New("generated files are out of date")
	regionPattern  = regexp.MustCompile(`^[a-z0-9]+(?:-[a-z0-9]+)*$`)
	repositoryPart = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.-]*$`)
	roleARNPattern = regexp.MustCompile(`^arn:(aws|aws-us-gov|aws-cn):iam::([0-9]{12}):role/([A-Za-z0-9+=,.@_/-]+)$`)
	pinSHAPattern  = regexp.MustCompile(`^[0-9a-f]{40}$`)
)

const generatedHeader = "# Code generated by artifact-pages registry setup"

// Options are explicit so setup does not consult environment-based config
// locators, AWS credentials, or other machine state.
type Options struct {
	Directory       string
	ConfigPath      string
	TerraformOutput string
	Repository      string
	Check           bool
	Output          io.Writer
}

type templateData struct {
	CLI                  string
	Provider             string
	AWSRegion            string
	CloudflareEnv        []string
	PreviewCloudflareEnv []string
	PublishSHA           string
	PublishVersion       string
	PreviewSHA           string
	PreviewVersion       string
	RegistrySHA          string
	RegistryVersion      string
	AWSCredsSHA          string
	AWSCredsVersion      string
	RolesHash            string
}

type actionPin struct {
	SHA     string
	Version string
}

// These peeled tag commits were read from the official repositories when IMP-73
// was implemented. Keeping the values in source makes setup reproducible and
// usable without network access. Update this table only with a reviewed release.
