var githubSluggerAllowedRanges = [...]unicodeScalarRange{
	{0x203F, 0x2040}, {0x2054, 0x2054}, {0x24B6, 0x24E9}, {0xFE33, 0xFE34},
	{0xFE4D, 0xFE4F}, {0xFF3F, 0xFF3F}, {0x1F130, 0x1F149}, {0x1F150, 0x1F169},
	{0x1F170, 0x1F189},
}

func githubSluggerCharacterAllowed(character rune) bool {
	if inUnicodeScalarRanges(githubSluggerRejectedRanges[:], character) {
		return false
	}
	if inUnicodeScalarRanges(githubSluggerAllowedRanges[:], character) {
		return true
	}
	return character == ' ' || character == '-' || character == '_' ||
		unicode.IsLetter(character) || unicode.IsMark(character) || unicode.IsDigit(character) ||
		unicode.Is(unicode.Nl, character)
}

func inUnicodeScalarRanges(ranges []unicodeScalarRange, character rune) bool {
	index := sort.Search(len(ranges), func(index int) bool {
		return ranges[index].last >= character
	})
	return index < len(ranges) && ranges[index].first <= character
}
